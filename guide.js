// Kurzfassung einer Übung: gemeinsame Kurzfassung des Musters, ersetzt durch die eigene (SHORT_EX)
const shortFor = (name, pattern) => ({ ...(FIG_TEXT[pattern] || {}), ...(SHORT_EX[name] || {}) });

// Ausführliche Anleitung einer Übung: Muster-Abschnitte, ersetzt durch die der Übung
function guideFor(name, pattern) {
  const base = GUIDE_PAT[pattern] || null;
  const own = GUIDE_EX[name] || null;
  if (!base && !own) return null;
  return { ...(base || {}), ...(own || {}) };
}

// Aufklappbarer Block „📖 Ausführlicher“ unter der Kurzfassung
function guideHtml(name, pattern) {
  const g = guideFor(name, pattern);
  if (!g) return '';
  const list = (title, arr, tag = 'ul') => arr && arr.length ? `<h3>${title}</h3><${tag}>${arr.map(s => `<li>${esc(s)}</li>`).join('')}</${tag}>` : '';
  return `<details class="card lib-guide"><summary>📖 Ausführlicher</summary>
    ${list('Einstellen und Ausgangsposition', g.setup)}
    ${list('Ausführung', g.steps, 'ol')}
    ${g.breath ? `<h3>Atmung</h3><p>${esc(g.breath)}</p>` : ''}
    ${list('Häufige Fehler', g.mistakes)}
    ${g.safety ? `<h3>Sicherheit</h3><p>${esc(g.safety)}</p>` : ''}
  </details>`;
}
